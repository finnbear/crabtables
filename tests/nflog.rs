use crabtables::*;

/// Create `table inet t` with an output chain logging UDP packets to
/// `port` into `group`.
fn setup_log_rules(rules: &[(u16, u16, Option<u16>)]) {
    let mut s = Socket::new().unwrap();
    let mut b = Batch::new();
    b.add_table(&Table::new(Family::Inet, "t"));
    b.add_chain(&Chain::new(Family::Inet, "t", "out").with_hook(
        ChainType::Filter,
        Hook::OUTPUT,
        0,
    ));
    for &(port, group, qthresh) in rules {
        let log = expr::Log {
            group: Some(group),
            prefix: Some(format!("port{port}")),
            qthreshold: qthresh,
            ..Default::default()
        };
        b.add_rule(
            &RuleBuilder::new(Family::Inet, "t", "out")
                .match_eq(Field::UdpDport, port)
                .log(log)
                .build(),
        );
    }
    s.commit(&b).unwrap();
}

fn sender() -> UdpSocket {
    UdpSocket::bind("127.0.0.1:0").unwrap()
}

fn sink(port: u16) -> UdpSocket {
    UdpSocket::bind(("127.0.0.1", port)).unwrap()
}

/// Receive until `n` packets were collected (with a timeout).
fn collect(s: &mut NflogSocket, n: usize) -> Vec<OwnedPacket> {
    let mut v = Vec::new();
    let deadline = std::time::Instant::now() + Duration::from_secs(5);
    while v.len() < n {
        assert!(
            std::time::Instant::now() < deadline,
            "timeout: got {} of {n} packets",
            v.len()
        );
        match s.try_recv().unwrap() {
            Some(pkts) => {
                for p in pkts {
                    v.push(p.unwrap().to_owned());
                }
            }
            None => std::thread::sleep(Duration::from_millis(1)),
        }
    }
    v
}

#[test]
fn receive_packets() {
    netns();
    setup_log_rules(&[(9999, 7, None)]);
    let _sink = sink(9999);
    let mut log = NflogSocket::new().unwrap();
    log.bind(&GroupConfig::new(7)).unwrap();

    let tx = sender();
    for i in 0..10u8 {
        tx.send_to(&[i; 32], "127.0.0.1:9999").unwrap();
    }
    let pkts = collect(&mut log, 10);
    for (i, p) in pkts.iter().enumerate() {
        assert_eq!(p.group, 7);
        assert_eq!(p.family, sys::NFPROTO_IPV4);
        assert_eq!(p.hook, sys::NF_INET_LOCAL_OUT as u8);
        assert_eq!(p.prefix.as_deref(), Some(&b"port9999"[..]));
        assert_eq!(p.outdev, Some(1), "lo is ifindex 1");
        assert_eq!(p.indev, None);
        assert_eq!(p.seq, Some(i as u32));
        // IPv4 header (20) + UDP header (8) + payload (32)
        assert_eq!(p.payload.len(), 60);
        assert_eq!(p.payload[0] >> 4, 4);
        assert_eq!(&p.payload[28..], &[i as u8; 32]);
        assert_eq!(p.uid, Some(0), "locally generated by root");
        assert_eq!(p.gid, Some(0));
    }
    let st = log.stats();
    assert_eq!(st.received, 10);
    assert_eq!(st.lost, 0);
    assert_eq!(st.overruns, 0);
}

#[test]
fn copy_modes_and_snaplen() {
    netns();
    setup_log_rules(&[(9999, 7, None)]);
    let _sink = sink(9999);
    let mut log = NflogSocket::new().unwrap();
    log.bind(&GroupConfig::new(7).copy_mode(CopyMode::Packet(10)))
        .unwrap();
    let tx = sender();
    tx.send_to(&[1; 100], "127.0.0.1:9999").unwrap();
    let p = collect(&mut log, 1);
    assert_eq!(p[0].payload.len(), 10);

    log.configure(&GroupConfig::new(7).copy_mode(CopyMode::Meta))
        .unwrap();
    tx.send_to(&[1; 100], "127.0.0.1:9999").unwrap();
    let p = collect(&mut log, 1);
    assert!(p[0].payload.is_empty());
    assert_eq!(p[0].prefix.as_deref(), Some(&b"port9999"[..]));
}

/// Flood a socket with a tiny receive buffer: the kernel drops messages and
/// reports ENOBUFS. Sequence numbers must account for every lost packet.
#[test]
fn overflow_is_counted_exactly() {
    netns();
    setup_log_rules(&[(9999, 7, None)]);
    let _sink = sink(9999);
    let mut log = NflogSocket::new().unwrap();
    log.set_recv_buffer_size(4096).unwrap();
    log.bind(&GroupConfig::new(7)).unwrap();

    let tx = sender();
    const N: u64 = 3000;
    for _ in 0..N {
        tx.send_to(&[0; 200], "127.0.0.1:9999").unwrap();
    }
    // Drain what fitted.
    while let Some(pkts) = log.try_recv().unwrap() {
        for p in pkts {
            p.unwrap();
        }
    }
    // Losses at the tail are detected when the next packet arrives.
    tx.send_to(&[0; 200], "127.0.0.1:9999").unwrap();
    collect(&mut log, 1);
    let st = log.stats();
    assert!(st.overruns >= 1, "{st:?}");
    assert!(st.lost > 0, "{st:?}");
    assert_eq!(st.received + st.lost, N + 1, "{st:?}");
}

/// Separate sockets for separate groups receive only their own packets, and
/// an nf_tables socket can be used at the same time.
#[test]
fn multiple_sockets_are_isolated() {
    netns();
    setup_log_rules(&[(9999, 7, None), (9998, 8, None)]);
    let (_s1, _s2) = (sink(9999), sink(9998));
    let mut a = NflogSocket::new().unwrap();
    let mut b = NflogSocket::new().unwrap();
    a.bind(&GroupConfig::new(7)).unwrap();
    b.bind(&GroupConfig::new(8)).unwrap();

    // A second socket cannot bind a group that is taken.
    let mut c = NflogSocket::new().unwrap();
    let err = c.bind(&GroupConfig::new(7)).unwrap_err();
    assert_eq!(err.errno(), Some(libc::EPERM), "{err}");
    // Binding twice from the same socket is EBUSY.
    assert_eq!(
        a.bind(&GroupConfig::new(7)).unwrap_err().errno(),
        Some(libc::EBUSY)
    );

    let mut nft_sock = Socket::new().unwrap();
    let tx = sender();
    for _ in 0..5 {
        tx.send_to(b"a", "127.0.0.1:9999").unwrap();
        tx.send_to(b"b", "127.0.0.1:9998").unwrap();
        // Use the nf_tables socket concurrently.
        assert_eq!(nft_sock.list_tables(Family::Inet).unwrap().len(), 1);
    }
    let pa = collect(&mut a, 5);
    let pb = collect(&mut b, 5);
    assert!(pa.iter().all(|p| p.group == 7 && p.payload.ends_with(b"a")));
    assert!(pb.iter().all(|p| p.group == 8 && p.payload.ends_with(b"b")));
    std::thread::sleep(Duration::from_millis(50));
    assert!(a.try_recv().unwrap().is_none());
    assert!(b.try_recv().unwrap().is_none());

    // After unbinding, another socket can take the group.
    a.unbind(7).unwrap();
    c.bind(&GroupConfig::new(7)).unwrap();
    tx.send_to(b"c", "127.0.0.1:9999").unwrap();
    let pc = collect(&mut c, 1);
    assert_eq!(pc[0].seq, Some(0), "sequence restarts for a new instance");
}

/// With a queue threshold, the kernel batches several packets per datagram.
#[test]
fn batched_delivery() {
    netns();
    setup_log_rules(&[(9999, 9, Some(5))]);
    let _sink = sink(9999);
    let mut log = NflogSocket::new().unwrap();
    log.bind(
        &GroupConfig::new(9)
            .qthresh(5)
            .timeout(Duration::from_millis(100)),
    )
    .unwrap();
    let tx = sender();
    for _ in 0..10 {
        tx.send_to(b"x", "127.0.0.1:9999").unwrap();
    }
    let mut datagrams = 0;
    let mut n = 0;
    let deadline = std::time::Instant::now() + Duration::from_secs(5);
    while n < 10 {
        assert!(std::time::Instant::now() < deadline);
        if let Some(pkts) = log.try_recv().unwrap() {
            datagrams += 1;
            for p in pkts {
                p.unwrap();
                n += 1;
            }
        } else {
            std::thread::sleep(Duration::from_millis(5));
        }
    }
    assert_eq!(n, 10);
    assert!(
        datagrams <= 3,
        "expected batching, got {datagrams} datagrams"
    );
    assert_eq!(log.stats().lost, 0);

    // The flush timeout delivers a partial batch.
    tx.send_to(b"y", "127.0.0.1:9999").unwrap();
    collect(&mut log, 1);
}

#[test]
fn blocking_recv() {
    netns();
    setup_log_rules(&[(9999, 7, None)]);
    let _sink = sink(9999);
    let mut log = NflogSocket::new().unwrap();
    log.bind(&GroupConfig::new(7).seq_global(true)).unwrap();
    let tx = sender();
    tx.send_to(b"hello", "127.0.0.1:9999").unwrap();
    let pkts: Vec<_> = log.recv().unwrap().map(|p| p.unwrap().to_owned()).collect();
    assert_eq!(pkts.len(), 1);
    assert!(pkts[0].seq_global.is_some());
    assert!(pkts[0].payload.ends_with(b"hello"));
}

#[test]
fn recv_timeout() {
    netns();
    let mut log = NflogSocket::new().unwrap();
    log.bind(&GroupConfig::new(11)).unwrap();
    log.set_recv_timeout(Some(Duration::from_millis(50)))
        .unwrap();
    let t = std::time::Instant::now();
    let e = log.recv().map(|_| ()).unwrap_err();
    assert!(
        matches!(&e, Error::Io(io) if io.kind() == std::io::ErrorKind::WouldBlock),
        "{e}"
    );
    assert!(t.elapsed() >= Duration::from_millis(40));
    // The socket keeps working afterwards.
    log.set_recv_timeout(None).unwrap();
    assert!(log.try_recv().unwrap().is_none());
}

/// A failed re-bind keeps the loss accounting of the existing binding.
#[test]
fn failed_rebind_keeps_tracking() {
    netns();
    setup_log_rules(&[(9999, 7, None)]);
    let _sink = sink(9999);
    let mut log = NflogSocket::new().unwrap();
    log.bind(&GroupConfig::new(7)).unwrap();
    let tx = sender();
    for i in 0..10u8 {
        tx.send_to(&[i; 8], "127.0.0.1:9999").unwrap();
    }
    collect(&mut log, 10);
    assert!(log.bind(&GroupConfig::new(7)).is_err());
    for i in 0..10u8 {
        tx.send_to(&[i; 8], "127.0.0.1:9999").unwrap();
    }
    let pkts = collect(&mut log, 10);
    assert_eq!(pkts[0].seq, Some(10));
    assert_eq!(log.stats().lost, 0);
}

/// A configuration request whose ack is dropped by a full receive buffer
/// fails instead of waiting forever.
#[test]
fn config_ack_lost_to_overrun() {
    netns();
    setup_log_rules(&[(9999, 7, None)]);
    let _sink = sink(9999);
    let mut log = NflogSocket::new().unwrap();
    log.set_recv_buffer_size(4096).unwrap();
    log.bind(&GroupConfig::new(7)).unwrap();
    let tx = sender();
    for _ in 0..200 {
        tx.send_to(&[0; 512], "127.0.0.1:9999").unwrap();
    }
    let (done, wait) = std::sync::mpsc::channel();
    let t = std::thread::spawn(move || {
        let start = std::time::Instant::now();
        let r = log.configure(&GroupConfig::new(7));
        done.send(()).unwrap();
        (r, start.elapsed(), log.stats())
    });
    assert!(wait.recv_timeout(Duration::from_secs(10)).is_ok(), "hangs");
    let (r, took, st) = t.join().unwrap();
    eprintln!("{r:?} after {took:?}, {st:?}");
    assert!(st.overruns > 0);
    if let Err(e) = r {
        assert!(
            matches!(&e, Error::Io(e) if e.kind() == std::io::ErrorKind::TimedOut),
            "{e}"
        );
    }
}
